import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const src=await readFile(new URL('../js/listing-plan.js',import.meta.url));
const {buildPlan}=await import('data:text/javascript;base64,'+src.toString('base64'));
const issue=(field,heading,severity,penalty)=>({field,heading,severity,penalty,detail:'Verify details'});
const current={score:53,market:'Etsy',issues:[issue('edit-tags','Underused tags','important',10),issue('edit-tags','Repeated tags','important',11),issue('edit-price','Invalid price','critical',16),issue('edit-title','Weak title','important',10)]};
const baseline={score:48,issues:[...current.issues,issue('edit-dimensions','Missing size','minor',5)]};
const row=(phrase,score,tagEligible,coverage)=>({phrase,score,tagEligible,coverage});
const kw={tagCount:3,rows:[row('gold tone bracelet',90,true,{title:true,description:false,tag:false}),row('bracelet',90,true,{title:true,tag:false}),row('new unsupported phrase',99,true,{title:false,description:false,tag:false}),row('existing tag',99,true,{title:true,tag:true}),row('oversized phrase here',99,false,{title:true,tag:false})]};
const data=buildPlan(current,baseline,kw,{currency:'GBP',date:'2026-11-24',difference:-6});
assert.deepEqual(data.actions.map(x=>x.field),['edit-price','edit-tags','edit-title']);
assert.equal(data.actions[1].points,21);assert.equal(data.actions[1].findings[0].heading,'Repeated tags');
assert.deepEqual(data.keywords,[{phrase:'gold tone bracelet',source:'Title',score:90}]);assert.equal(data.slots,10);
assert.deepEqual(data.progress,{savedScore:48,currentScore:53,change:5,cleared:1,total:5});
assert.match(data.price.advice,/margin/);
assert.equal(buildPlan(current,null,kw,null).progress,null);
assert.equal(buildPlan(current,null,kw,{currency:'USD',date:'invalid',difference:5}).price,null);
assert.deepEqual(buildPlan({...current,market:'Amazon'},null,kw,null).keywords,[]);
assert.equal(buildPlan({...current,market:'Amazon'},null,kw,null).slots,null);
assert.equal(buildPlan(current,null,{...kw,tagCount:14},null).slots,0);
assert.equal(buildPlan({...current,issues:[]},baseline,kw,null).actions.length,0);
console.log('PASS: priority grouping, eligible own-wording suggestions, honest baseline, price evidence, marketplace scope and empty states.');
