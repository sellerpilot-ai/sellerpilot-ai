import assert from 'node:assert/strict';
import {previewEtsyCatalogue as preview} from '../js/etsy-import-preview.js';
const row={shop_id:1,listing_id:2,title:'Example',tags:['gift'],aiAllowed:true,secret:'ignored'};
const payload={results:[row]};
