import {planSyntheticCatalogueImport as plan} from '../js/etsy-import-preview.js';
const sample={fixtureId:'sample-bracelet',title:'Fictional bracelet',description:'Sample only',tags:['bracelet'],sku:'S-01',priceMinor:1850,currency:'GBP',token:'discard',aiAllowed:true};
const fixture=listings=>({source:'synthetic-fixture',listings});
const ready=plan(fixture([sample]))[0];
assert.deepEqual(ready,{fixtureId:'sample-bracelet',status:'ready',reason:'Ready for review',title:'Fictional bracelet',description:'Sample only',tags:['bracelet'],sku:'S-01',priceMinor:1850,currency:'GBP'});
assert.notEqual(ready.tags,sample.tags);
assert.equal(plan(fixture([sample]),[{title:' fictional  BRACELET '}])[0].status,'duplicate');
assert.equal(plan(fixture([sample]),[{sku:'s-01'}])[0].reason,'Matching SKU');
assert.equal(plan(fixture([sample]),[{fixtureId:sample.fixtureId}])[0].reason,'Fixture identity already present');
assert.equal(plan(fixture([sample,{...sample,fixtureId:'sample-other',title:'Other'}]))[1].status,'duplicate');
assert.equal(plan(fixture([{...sample,priceMinor:0}]))[0].status,'invalid');
assert.equal(plan(fixture([{...sample,currency:'EUR'}]))[0].status,'invalid');
assert.equal(plan(fixture([{...sample,tags:['bad\ntext']}]))[0].status,'invalid');
assert.throws(()=>plan(fixture([sample,sample])));
assert.throws(()=>plan({source:'etsy-api',listings:[sample]}));
assert.throws(()=>plan(fixture([{...sample,fixtureId:'12345'}])));
assert.throws(()=>plan(fixture(Array.from({length:51},(_,i)=>({...sample,fixtureId:'sample-'+i})))));
assert.deepEqual(plan(fixture([])),[]);
console.log('PASS synthetic-only import design: identity, duplicate title/SKU, invalid price/currency/tags, bounds and data minimisation.');
