import assert from 'node:assert/strict';
import {discover} from '../js/keyword-discovery.mjs';
const p={title:'Minimalist Gold Tone Bracelet',description:'Simple bracelet for everyday wear.',tags:'bracelet, gold jewellery, BRACELET, excessively long keyword phrase'};
const d=discover(p,'gold tone bracelet','birthday gift');
assert.deepEqual(d.duplicates,[{phrase:'bracelet',count:2}]);
assert.equal(d.uniqueTags,3);
assert.equal(d.overlength.length,1);
const main=d.rows.find(x=>x.phrase==='gold tone bracelet');
assert.equal(main.score,100);
assert.equal(main.longTail,true);
assert.equal(main.coverage.title,true);
assert.equal(main.coverage.tag,false);
assert.equal(main.tagEligible,true);
const gift=d.rows.find(x=>x.phrase==='birthday gift');
assert.equal(gift.intent,'Gift / occasion');
assert.ok(gift.score<main.score);
assert.equal(gift.coverage.title,false);
assert.ok(d.rows.some(x=>x.phrase==='birthday gift gold tone bracelet'&&!x.tagEligible));
assert.equal(new Set(d.rows.map(x=>x.phrase)).size,d.rows.length);
assert.ok(d.rows.every(x=>x.score>=0&&x.score<=100));
assert.ok(d.rows.every(x=>!('search_volume' in x)&&!('competition' in x)));
assert.deepEqual(discover(null).rows,[]);
const q=discover(null,'custom necklace','initial');
assert.ok(q.rows.some(x=>x.intent==='Personalisation'));
assert.equal(discover({title:'bracelet',description:'bracelets',tags:'bracelets'},'bracelet').rows.find(x=>x.phrase==='bracelet').coverage.description,false);
assert.equal(discover(null,'x'.repeat(21)).rows[0].tagEligible,false);
assert.deepEqual(discover(p,'gold tone bracelet','birthday gift'),d);
console.log('PASS: deterministic local ideas, intent, exact phrase coverage, tag length, duplicate tags and relevance.');
