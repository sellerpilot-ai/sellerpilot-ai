import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const source=await readFile(new URL('../js/competitor-comparison.js',import.meta.url));
const {compareListings}=await import('data:text/javascript;base64,'+source.toString('base64'));
const own={title:'Gold tone bracelet',description:'A birthday gift',tags:'bracelet,gold jewellery,BRACELET',price:18.5,currency:'GBP',facts:'gift box, adjustable clasp'};
const rival={title:'Gold bracelet',price:'24.50',currency:'GBP',tagsKnown:true,tags:'bracelet,birthday gift,very long descriptive keyword',facts:'gift box'};
const d=compareListings(own,rival);
assert.equal(d.price.difference,-6);
assert.equal(d.price.percentage,-24.5);
assert.deepEqual(d.shared,['bracelet']);
assert.deepEqual(d.ownOnly,['gold jewellery']);
assert.deepEqual(d.gaps,[{phrase:'birthday gift',ownTitle:false,ownDescription:true,tagEligible:true},{phrase:'very long descriptive keyword',ownTitle:false,ownDescription:false,tagEligible:false}]);
assert.deepEqual(d.distinct,['adjustable clasp']);
assert.equal(compareListings(own,{...rival,currency:'USD'}).price.difference,null);
assert.equal(compareListings(own,{...rival,price:''}).price.rival,null);
assert.equal(compareListings(own,{...rival,price:0}).price.percentage,null);
assert.equal(compareListings(own,{...rival,price:-1}).price.rival,null);
const unknown=compareListings(own,{...rival,tagsKnown:false});assert.equal(unknown.known,false);assert.deepEqual(unknown.gaps,[]);assert.deepEqual(unknown.ownOnly,[]);
assert.throws(()=>compareListings(own,{title:''}));
assert.deepEqual(compareListings(own,rival),d);
console.log('PASS: same-currency cents, missing prices, zero, exact normalized tags, unknown-data handling, differentiators and deterministic comparison.');
