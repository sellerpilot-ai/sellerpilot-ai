import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {createPendingAuthorization,authorizationUrl,validCallback} from '../server/etsy-oauth-primitives.mjs';
const p=createPendingAuthorization('user-a',1000);
assert.match(p.verifier,/^[A-Za-z0-9_-]{43}$/);
assert.equal(p.challenge,createHash('sha256').update(p.verifier).digest('base64url'));
assert.notEqual(p.state,createPendingAuthorization('user-a',1000).state);
const uri='https://example.invalid/callback';
const u=new URL(authorizationUrl(p,'mock-client',uri));
assert.equal(u.origin,'https://www.etsy.com');
assert.equal(u.searchParams.get('scope'),'listings_r shops_r');
assert.equal(u.searchParams.get('redirect_uri'),uri);
assert.equal(u.searchParams.get('code_challenge_method'),'S256');
assert.equal(u.searchParams.get('state'),p.state);
assert.equal(u.searchParams.has('code_verifier'),false);
assert.equal(validCallback(p,'user-a',p.state,1001),true);
assert.equal(validCallback(p,'user-b',p.state,1001),false);
assert.equal(validCallback(p,'user-a','invalid',1001),false);
assert.equal(validCallback(p,'user-a',p.state,601000),false);
assert.throws(()=>authorizationUrl(p,'mock-client','http://example.invalid/callback'));
assert.throws(()=>createPendingAuthorization('',1000));
console.log('PASS V73 offline OAuth fixtures');

const {createMockStateStore}=await import('../server/etsy-oauth-primitives.mjs');
const store=createMockStateStore(1);
const issued=store.issue('user-a',1000);
assert.equal(store.consume('user-b',issued.state,1001),null);
assert.throws(()=>store.issue('user-b',1001));
assert.equal(store.consume('user-a',issued.state,1002).verifier,issued.verifier);
assert.equal(store.consume('user-a',issued.state,1003),null);
const expired=store.issue('user-a',2000);
assert.equal(store.consume('user-a',expired.state,602000),null);
assert.ok(store.issue('user-b',602000));
console.log('PASS V73 single-use state fixtures');

assert.equal(validCallback(p,'user-a',p.state,999),false);
assert.equal(validCallback({...p,expiresAt:p.expiresAt+1},'user-a',p.state,1001),false);
assert.throws(()=>createPendingAuthorization('user-a',Number.MAX_SAFE_INTEGER));
assert.throws(()=>authorizationUrl({...p,challenge:'forged'},'mock-client',uri));
assert.throws(()=>authorizationUrl({...p,verifier:'invalid'},'mock-client',uri));
assert.throws(()=>authorizationUrl(p,'mock-client','https://user:pass@example.invalid/callback'));
assert.throws(()=>authorizationUrl(p,'mock-client','https://example.invalid/callback#fragment'));
console.log('PASS V77/V78 OAuth context, timestamp and PKCE integrity fixtures');
